#!/usr/bin/env node
/**
 * Regenerates THIRD_PARTY_NOTICES.md from the installed production dependencies:
 *   npm run notices
 * Keeps each package's copyright line and licence text (and NOTICE file, where it has one).
 * Fails (exit 1) if a copyleft / SSPL licence appears, so CI catches it.
 */
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

// The scanner runs through npx on purpose: it is NOT a project dependency, so it cannot add
// (dev) vulnerabilities to our own `npm audit`.
function scan() {
  const json = execFileSync("npx", ["--yes", "license-checker-rseidelsohn", "--production", "--excludePrivatePackages", "--json"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "ignore"] });
  return JSON.parse(json);
}

{
  const pkgs = scan();
  const names = Object.keys(pkgs).sort();
  const bad = names.filter((n) => /GPL|SSPL|AGPL|LGPL/i.test(String(pkgs[n].licenses)));
  const counts = {};
  for (const n of names) counts[pkgs[n].licenses] = (counts[pkgs[n].licenses] || 0) + 1;

  let out = "# Third-party notices\n\nGenerated by `npm run notices` from the installed production dependencies. Do not edit by hand.\n\n## Summary\n\n";
  out += Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, c]) => `- ${l}: ${c}`).join("\n") + "\n\n## Packages\n\n| Package | Licence | Source |\n|---|---|---|\n";
  for (const n of names) out += `| ${n} | ${pkgs[n].licenses} | ${pkgs[n].repository || ""} |\n`;
  out += "\n## Licence texts\n";
  for (const n of names) {
    const p = pkgs[n];
    let text = "";
    if (p.licenseFile && fs.existsSync(p.licenseFile) && !/README/i.test(path.basename(p.licenseFile))) text = fs.readFileSync(p.licenseFile, "utf8").trim();
    out += `\n### ${n} (${p.licenses})\n\n`;
    out += text ? "```\n" + text + "\n```\n" : "_No licence file shipped in the package; licence taken from package metadata._\n";
    if (p.noticeFile && fs.existsSync(p.noticeFile)) out += "\nNOTICE:\n\n```\n" + fs.readFileSync(p.noticeFile, "utf8").trim() + "\n```\n";
  }
  fs.writeFileSync("THIRD_PARTY_NOTICES.md", out);
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${names.length} packages).`);
  if (bad.length) { console.error("Copyleft/SSPL licence found:", bad.join(", ")); process.exit(1); }
}
